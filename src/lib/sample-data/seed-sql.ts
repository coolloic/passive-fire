import type { CatalogueSolution } from "../catalogue/parse.ts";
import { sqlLiteral } from "../catalogue/seed-sql.ts";
import {
  SAMPLE_CREWS,
  SAMPLE_DELIVERIES,
  SAMPLE_PERSONAS,
  SAMPLE_PLANNED_WORK,
  SAMPLE_SCENARIOS,
  SAMPLE_SITE,
  SAMPLE_STOCK,
  type SampleScenario,
} from "./site.ts";

/** SQL date expression relative to the day the seed is loaded. */
export function relativeDate(offset: number): string {
  if (offset === 0) return "current_date";
  return `current_date ${offset > 0 ? "+" : "-"} ${Math.abs(offset)}`;
}

function scenarioAttributes(scenario: SampleScenario, solutions: Map<string, CatalogueSolution>) {
  if (scenario.nominatedCode === null) {
    if (!scenario.attributes) throw new Error(`Scenario ${scenario.key} needs attributes`);
    return scenario.attributes;
  }
  const solution = solutions.get(scenario.nominatedCode);
  if (!solution)
    throw new Error(
      `Scenario ${scenario.key} nominates unknown solution ${scenario.nominatedCode}`,
    );
  return {
    serviceType: solution.serviceTypeOption,
    serviceSize: solution.serviceSizeRaw,
    orientation: solution.orientation,
    substrate: solution.substrateOption,
    integrityMinutes: solution.integrityMinutes,
    insulationMinutes: solution.insulationMinutes,
  };
}

function values(rows: string[][]): string {
  return rows.map((row) => `  (${row.join(", ")})`).join(",\n");
}

/** Deterministic SQL for the SAMPLE site, demo personas, planned work and supply. */
export function renderSampleSiteSql(catalogue: readonly CatalogueSolution[]): string {
  const solutions = new Map(catalogue.map((solution) => [solution.internalCode, solution]));
  const scenarioIds = new Map(SAMPLE_SCENARIOS.map((scenario) => [scenario.key, scenario.id]));
  const lit = sqlLiteral;

  const users = values(
    SAMPLE_PERSONAS.map((persona) => [
      "'00000000-0000-0000-0000-000000000000'",
      lit(persona.id),
      "'authenticated'",
      "'authenticated'",
      lit(persona.email),
      // Random, unknowable password: demo sign-in is passwordless (see task 4.1).
      "extensions.crypt(gen_random_uuid()::text, extensions.gen_salt('bf'))",
      "now()",
      `'{"provider":"email","providers":["email"]}'`,
      "'{}'",
      "now()",
      "now()",
      "''",
      "''",
      "''",
      "''",
    ]),
  );
  const identities = values(
    SAMPLE_PERSONAS.map((persona) => [
      lit(persona.id),
      lit(persona.id),
      lit(persona.id),
      `jsonb_build_object('sub', ${lit(persona.id)}, 'email', ${lit(persona.email)}, 'email_verified', true)`,
      "'email'",
      "now()",
      "now()",
      "now()",
    ]),
  );
  const profiles = values(
    SAMPLE_PERSONAS.map((persona) => [
      lit(persona.id),
      lit(persona.displayName),
      lit(persona.role),
      "true",
    ]),
  );
  const scenarios = values(
    SAMPLE_SCENARIOS.map((scenario) => {
      const attributes = scenarioAttributes(scenario, solutions);
      return [
        lit(scenario.id),
        lit(SAMPLE_SITE.id),
        lit(scenario.label),
        lit(attributes.serviceType),
        lit(attributes.serviceSize),
        lit(attributes.orientation),
        lit(attributes.substrate),
        lit(attributes.integrityMinutes),
        lit(attributes.insulationMinutes),
      ];
    }),
  );
  const nominated = SAMPLE_SCENARIOS.filter((scenario) => scenario.nominatedCode !== null).map(
    (scenario) => [lit(scenario.id), lit(scenario.nominatedCode)],
  );
  const plannedWork = values(
    SAMPLE_PLANNED_WORK.map((work, index) => [
      lit(work.id),
      lit(work.crewId),
      lit(SAMPLE_SITE.id),
      relativeDate(work.dayOffset),
      // Creation order breaks same-date ties deterministically.
      `now() - interval '30 days' + interval '${index} minutes'`,
    ]),
  );
  const items = values(
    SAMPLE_PLANNED_WORK.flatMap((work) =>
      work.items.map((item) => {
        const scenarioId = scenarioIds.get(item.scenarioKey);
        if (!scenarioId)
          throw new Error(`Planned work ${work.key} uses unknown scenario ${item.scenarioKey}`);
        return [lit(work.id), lit(scenarioId), lit(item.penetrationCount)];
      }),
    ),
  );
  const stock = values(SAMPLE_STOCK.map((row) => [lit(row.sku), lit(row.quantity)]));
  const deliveries = values(
    SAMPLE_DELIVERIES.map((delivery) => [
      lit(delivery.id),
      lit(delivery.sku),
      lit(delivery.quantity),
      relativeDate(delivery.dayOffset),
    ]),
  );

  return [
    "-- GENERATED by `pnpm db:seed:generate` from src/lib/sample-data/site.ts. Do not edit by hand.",
    "-- SAMPLE site, demo personas, crews, planned work and supply. Dates are relative to load day.",
    "",
    "insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,",
    "  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,",
    "  email_change_token_new, email_change) values",
    `${users};`,
    "",
    "insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at,",
    "  created_at, updated_at) values",
    `${identities};`,
    "",
    "insert into public.profiles (id, display_name, role, is_sample) values",
    `${profiles};`,
    "",
    "insert into public.sites (id, name, is_sample) values",
    `  (${lit(SAMPLE_SITE.id)}, ${lit(SAMPLE_SITE.name)}, true);`,
    "",
    "insert into public.crews (id, name, team_leader_id) values",
    `${values(SAMPLE_CREWS.map((crew) => [lit(crew.id), lit(crew.name), lit(crew.teamLeaderId)]))};`,
    "",
    "insert into public.scenarios (id, site_id, label, service_type, service_size, orientation, substrate,",
    "  integrity_minutes, insulation_minutes) values",
    `${scenarios};`,
    "",
    "insert into public.nominated_solutions (scenario_id, solution_id)",
    "select v.scenario_id::uuid, s.id from (values",
    values(nominated),
    ") as v (scenario_id, internal_code)",
    "join public.solutions s on s.internal_code = v.internal_code;",
    "",
    "insert into public.planned_work (id, crew_id, site_id, work_date, created_at) values",
    `${plannedWork};`,
    "",
    "insert into public.planned_work_items (planned_work_id, scenario_id, penetration_count) values",
    `${items};`,
    "",
    "insert into public.stock (product_id, quantity)",
    "select p.id, v.quantity from (values",
    stock,
    ") as v (sku, quantity)",
    "join public.products p on p.sku = v.sku;",
    "",
    "insert into public.expected_deliveries (id, product_id, quantity, expected_date)",
    "select v.id::uuid, p.id, v.quantity, v.expected_date from (values",
    deliveries,
    ") as v (id, sku, quantity, expected_date)",
    "join public.products p on p.sku = v.sku;",
    "",
  ].join("\n");
}
