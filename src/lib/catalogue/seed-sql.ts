import type { CatalogueSolution } from "./parse.ts";

type SqlValue = string | number | boolean | null | string[];

/** Renders a value as a SQL literal. Strings are single-quoted with quotes doubled. */
export function sqlLiteral(value: SqlValue): string {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot render non-finite number ${value}`);
    return String(value);
  }
  if (Array.isArray(value)) {
    return value.length === 0
      ? "'{}'::text[]"
      : `array[${value.map(sqlLiteral).join(", ")}]::text[]`;
  }
  return `'${value.replace(/'/g, "''")}'`;
}

const SOLUTION_COLUMNS = [
  "internal_code",
  "supplier_ref_code",
  "supplier",
  "orientation",
  "substrate_raw",
  "service_classification",
  "service_type_raw",
  "service_size_raw",
  "integrity_raw",
  "insulation_raw",
  "service_type_option",
  "substrate_option",
  "shape",
  "diameter_mm",
  "width_mm",
  "height_mm",
  "substrate_type",
  "substrate_thickness_mm",
  "integrity_minutes",
  "insulation_minutes",
  "parse_flags",
] as const;

function solutionValues(solution: CatalogueSolution): SqlValue[] {
  return [
    solution.internalCode,
    solution.supplierRefCode,
    solution.supplier,
    solution.orientation,
    solution.substrateRaw,
    solution.serviceClassification,
    solution.serviceTypeRaw,
    solution.serviceSizeRaw,
    solution.integrityRaw,
    solution.insulationRaw,
    solution.serviceTypeOption,
    solution.substrateOption,
    solution.shape,
    solution.diameterMm,
    solution.widthMm,
    solution.heightMm,
    solution.substrateType,
    solution.substrateThicknessMm,
    solution.integrityMinutes,
    solution.insulationMinutes,
    solution.parseFlags,
  ];
}

/** Deterministic SQL inserting the catalogue, in source order. */
export function renderCatalogueSql(solutions: CatalogueSolution[]): string {
  const header = [
    "-- GENERATED by `pnpm db:seed:generate` from docs/solutions-excerpt.csv. Do not edit by hand.",
    `-- ${solutions.length} solutions from the supplied Ryanfire catalogue excerpt.`,
    "",
  ];
  if (solutions.length === 0) return `${header.join("\n")}\n`;
  const rows = solutions.map(
    (solution) => `  (${solutionValues(solution).map(sqlLiteral).join(", ")})`,
  );
  return [
    ...header,
    `insert into public.solutions (${SOLUTION_COLUMNS.join(", ")}) values`,
    `${rows.join(",\n")};`,
    "",
  ].join("\n");
}
