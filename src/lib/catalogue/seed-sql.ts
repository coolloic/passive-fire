type SqlValue = string | number | boolean | null | string[];

/** Renders a value as a SQL literal. Strings are single-quoted with quotes doubled. */
export function sqlLiteral(value: SqlValue): string {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot render non-finite number ${value}`);
    return String(value);
  }
  if (Array.isArray(value)) {
    return value.length === 0
      ? "'{}'::text[]"
      : `array[${value.map(sqlLiteral).join(", ")}]::text[]`;
  }
  return `'${value.replace(/'/g, "''")}'`;
}

const SOLUTION_COLUMNS = [
  "internal_code",
  "supplier_ref_code",
  "supplier",
  "orientation",
  "substrate_raw",
  "service_classification",
  "service_type_raw",
  "service_size_raw",
  "integrity_raw",
  "insulation_raw",
  "service_type_option",
  "substrate_option",
  "shape",
  "diameter_mm",
  "width_mm",
  "height_mm",
  "substrate_type",
  "substrate_thickness_mm",
  "integrity_minutes",
  "insulation_minutes",
  "parse_flags",
] as const;

function solutionValues(solution: CatalogueSolution): SqlValue[] {
  return [
    solution.internalCode,
    solution.supplierRefCode,
    solution.supplier,
    solution.orientation,
    solution.substrateRaw,
    solution.serviceClassification,
    solution.serviceTypeRaw,
    solution.serviceSizeRaw,
    solution.integrityRaw,
    solution.insulationRaw,
    solution.serviceTypeOption,
    solution.substrateOption,
    solution.shape,
    solution.diameterMm,
    solution.widthMm,
    solution.heightMm,
    solution.substrateType,
    solution.substrateThicknessMm,
    solution.integrityMinutes,
    solution.insulationMinutes,
    solution.parseFlags,
  ];
}

/** Deterministic SQL inserting the catalogue, in source order. */
export function renderCatalogueSql(solutions: CatalogueSolution[]): string {
  const header = [
    "-- GENERATED by `pnpm db:seed:generate` from docs/solutions-excerpt.csv. Do not edit by hand.",
    `-- ${solutions.length} solutions from the supplied Ryanfire catalogue excerpt.`,
    "",
  ];
  if (solutions.length === 0) return `${header.join("\n")}\n`;
  const rows = solutions.map(
    (solution) => `  (${solutionValues(solution).map(sqlLiteral).join(", ")})`,
  );
  return [
    ...header,
    `insert into public.solutions (${SOLUTION_COLUMNS.join(", ")}) values`,
    `${rows.join(",\n")};`,
    "",
  ].join("\n");
}

/** Deterministic SQL inserting SAMPLE products and their per-solution requirements. */
export function renderSampleProductsSql(
  products: readonly SampleProduct[],
  requirements: readonly ProductRequirementRow[],
): string {
  const lines = [
    "-- GENERATED by `pnpm db:seed:generate`. Do not edit by hand.",
    "-- SAMPLE products and product requirements: the supplied catalogue has no products column,",
    "-- so these come from the rules in docs/spec/slice-1.md §4 (assumptions A-1, A-6).",
    `-- ${products.length} products, ${requirements.length} requirements.`,
    "",
  ];
  if (products.length > 0) {
    const rows = products.map(
      (product) =>
        `  (${[product.sku, product.name, product.unit].map(sqlLiteral).join(", ")}, true)`,
    );
    lines.push(
      "insert into public.products (sku, name, unit, is_sample) values",
      `${rows.join(",\n")};`,
      "",
    );
  }
  if (requirements.length > 0) {
    const rows = requirements.map(
      (requirement) =>
        `  (${[requirement.internalCode, requirement.sku, requirement.quantityPerPenetration].map(sqlLiteral).join(", ")})`,
    );
    lines.push(
      "insert into public.product_requirements (solution_id, product_id, quantity_per_penetration, is_sample)",
      "select s.id, p.id, v.quantity, true",
      "from (values",
      rows.join(",\n"),
      ") as v (internal_code, sku, quantity)",
      "join public.solutions s on s.internal_code = v.internal_code",
      "join public.products p on p.sku = v.sku;",
      "",
    );
  }
  return lines.join("\n");
}
